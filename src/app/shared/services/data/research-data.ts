/** What a research unlocks: a station module, ship, equipment, equipment mod or other ware. */
export type ResearchUnlockKind = 'module' | 'ship' | 'equipment' | 'mod' | 'ware';

export interface ResearchUnlockData {
  id: string;
  kind: ResearchUnlockKind;
  name: string;
  /** set when an md script hands out the blueprint once the research is done, rather than the ware requiring it */
  script?: true;
}

export interface ResearchData {
  id: string;
  version: number;
  name: string;
  /** seconds */
  time: number;
  sortOrder: number;
  /** delivered to the headquarters */
  wares: { ware: string; amount: number }[];
  /** research ids done first */
  requires: string[];
  /** missiononly: granted by a mission, not researched at the HQ */
  missionOnly?: true;
  /** nocustomgamestart: offered once a story or event adds it */
  story?: true;
  /** hidden: not shown at the HQ */
  hidden?: true;
  unlocks: ResearchUnlockData[];
}

